"""Serialize polish_asr_eval_v2 smoke results to JSON, CSV, and Markdown."""

from __future__ import annotations

import csv
import json
from pathlib import Path
from typing import Any


def write_json(path: Path, payload: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        json.dumps(payload, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )


def write_alignment_csv(path: Path, rows: list[dict[str, Any]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fieldnames = [
        "model_id",
        "normalization_version",
        "op",
        "ref_span",
        "hyp_span",
        "ref_start",
        "ref_end",
        "hyp_start",
        "hyp_end",
        "edit_mass",
        "primary_category",
        "secondary_tags",
        "semantic_impact",
        "review_status",
        "rationale",
    ]
    with path.open("w", encoding="utf-8", newline="") as fh:
        writer = csv.DictWriter(fh, fieldnames=fieldnames)
        writer.writeheader()
        for row in rows:
            writer.writerow(row)


def _pct(rate: float) -> str:
    return f"{100.0 * rate:.1f}%"


def _model_profile(metrics: dict[str, Any], model_id: str, profile: str) -> dict:
    return metrics["models"][model_id]["profiles"][profile]


def render_comparison_markdown_v2(payload: dict[str, Any]) -> str:
    """Render Sections A–I from the metrics/taxonomy payload (no hardcoded scores)."""
    clip_id = payload["clip_id"]
    protocol = payload["evaluation_protocol"]
    models = payload["model_ids"]
    primary = payload["primary_normalization_version"]
    lines: list[str] = [
        f"# Smoke evaluation v2 — `{protocol}`",
        "",
        f"- **clip_id:** `{clip_id}`",
        f"- **evaluation_protocol:** `{protocol}`",
        f"- **evaluation_version:** `{payload['evaluation_version']}`",
        f"- **primary metric:** `wer` after `{primary}` "
        f"(`wer_pl_normalized_v1`)",
        f"- **api_used:** `{payload['api_used']}`",
        f"- **asr_inference_performed:** `{payload['asr_inference_performed']}`",
        "",
        "## A — Executive summary",
        "",
    ]

    primary_scores = {
        mid: _model_profile(payload, mid, primary)["wer"] for mid in models
    }
    basic_scores = {
        mid: _model_profile(payload, mid, "pl_basic_v1")["wer"] for mid in models
    }
    best_primary = min(primary_scores, key=primary_scores.get)
    best_basic = min(basic_scores, key=basic_scores.get)
    lines.extend(
        [
            f"On this single smoke clip, **{best_primary}** has the lower "
            f"normalized WER ({_pct(primary_scores[best_primary])}) under "
            f"`{primary}`. Under legacy `pl_basic_v1`, **{best_basic}** has "
            f"WER {_pct(basic_scores[best_basic])}.",
            "",
            "Meaning-changing errors that survive normalization (lexical/"
            "morphology/homophone/brand misspelling/hallucination) are listed "
            "in Sections E–F. Entity-level quantitative accuracy is "
            "**unavailable** without verified entity annotations.",
            "",
            "Conclusions are **not** general model rankings: N = 1 scripted "
            "recording, used during normalizer development (not an independent "
            "held-out set). Robustness across normalization profiles is shown "
            "in Section D.",
            "",
            "## B — Experimental setup",
            "",
            "| Item | Value |",
            "|---|---|",
            f"| Audio | `{payload['paths']['audio']}` |",
            f"| Reference | `{payload['paths']['reference']}` |",
            f"| Scribe hypothesis | `{payload['paths']['scribe']}` |",
            f"| Whisper hypothesis | `{payload['paths']['whisper']}` |",
            f"| Scribe model_id | `scribe_v2` |",
            f"| Whisper model_id | `whisper-large-v3-turbo` "
            f"(repo: `mlx-community/whisper-large-v3-turbo`) |",
            f"| Language | `pl` |",
            f"| Scoring | offline rescore only; no STT / no API |",
            f"| Post-processing | none on saved hypotheses |",
            f"| jiwer | `{payload['environment']['jiwer_version']}` |",
            f"| Python | `{payload['environment']['python_version']}` |",
            f"| Git commit | `{payload['environment'].get('git_commit') or 'n/a'}` |",
            f"| reference_sha256 | `{payload['hashes']['reference_sha256']}` |",
            f"| scribe_sha256 | `{payload['hashes']['scribe_sha256']}` |",
            f"| whisper_sha256 | `{payload['hashes']['whisper_sha256']}` |",
            f"| audio_sha256 | `{payload['hashes']['audio_sha256']}` |",
            "",
            "This report was generated by re-scoring frozen transcripts. "
            "**No ASR inference was performed during report generation.**",
            "",
            "## C — Metrics comparison",
            "",
            "Primary metric: **WER after `pl_wer_normalized_v1`**.",
            "",
            "| Model | Basic WER | Numbers WER | Normalized WER | "
            "Basic CER | Normalized CER | Norm S/D/I | Norm N_ref |",
            "|---|---:|---:|---:|---:|---:|---:|---:|",
        ]
    )

    for mid in models:
        b = _model_profile(payload, mid, "pl_basic_v1")
        n = _model_profile(payload, mid, "pl_numbers_v1")
        v = _model_profile(payload, mid, primary)
        lines.append(
            "| {mid} | {bw} | {nw} | {vw} | {bc} | {vc} | {s}/{d}/{i} | {nn} |".format(
                mid=mid,
                bw=_pct(b["wer"]),
                nw=_pct(n["wer"]),
                vw=_pct(v["wer"]),
                bc=_pct(b["cer"]),
                vc=_pct(v["cer"]),
                s=v["substitutions"],
                d=v["deletions"],
                i=v["insertions"],
                nn=v["n_words_ref"],
            )
        )

    if payload.get("primary_metric_status") == "experimental":
        lines.extend(
            [
                "",
                "> **Status:** primary normalized metric is marked "
                "**experimental** due to unresolved safety findings "
                f"({payload.get('primary_metric_warning', 'see warnings')}).",
            ]
        )

    lines.extend(
        [
            "",
            "## D — Normalization sensitivity",
            "",
            "WER change is computed from actual scorer outputs "
            "(basic → normalized), not from summing taxonomy tags.",
            "",
            "| Model | Basic WER | Numbers WER | Normalized WER | "
            "Δ basic→norm (pp) |",
            "|---|---:|---:|---:|---:|",
        ]
    )
    for mid in models:
        b = _model_profile(payload, mid, "pl_basic_v1")
        n = _model_profile(payload, mid, "pl_numbers_v1")
        v = _model_profile(payload, mid, primary)
        delta_pp = 100.0 * (v["wer"] - b["wer"])
        lines.append(
            f"| {mid} | {_pct(b['wer'])} | {_pct(n['wer'])} | "
            f"{_pct(v['wer'])} | {delta_pp:+.1f} |"
        )

    sens = payload.get("normalization_sensitivity", {})
    lines.extend(["", "### Ablation (enabled-rule subsets)", ""])
    if sens:
        lines.append(
            "| Model | Rules enabled | WER | S | D | I | N |"
        )
        lines.append("|---|---|---:|---:|---:|---:|---:|")
        for mid, rows in sens.items():
            for row in rows:
                lines.append(
                    "| {mid} | {rules} | {wer} | {s} | {d} | {i} | {n} |".format(
                        mid=mid,
                        rules=row["rules_label"],
                        wer=_pct(row["wer"]),
                        s=row["substitutions"],
                        d=row["deletions"],
                        i=row["insertions"],
                        n=row["n_words_ref"],
                    )
                )
    else:
        lines.append("_No ablation rows recorded._")

    lines.extend(
        [
            "",
            "Format differences that normalization removes typically include "
            "written vs verbalized numbers, `%` vs `procent`, currency "
            "abbreviations, and unambiguous brand spacing. Remaining errors "
            "are lexical/morphological, homophones, brand misspellings, and "
            "insertions.",
            "",
            "## E — Error analysis",
            "",
            "Auto-inferred labels only (`review_status=auto_inferred`). "
            "Alignment under primary profile `{primary}`.".format(primary=primary),
            "",
        ]
    )

    taxonomy = payload.get("taxonomy", {})
    for mid in models:
        lines.extend([f"### {mid}", ""])
        edits = taxonomy.get(mid, {}).get("edits", [])
        if not edits:
            lines.append("_No remaining edits under the primary profile._")
            lines.append("")
            continue
        lines.extend(
            [
                "| Ref span | Hyp span | Op | Category | Impact | Review | Explanation |",
                "|---|---|---|---|---|---|---|",
            ]
        )
        for e in edits:
            lines.append(
                "| {ref} | {hyp} | {op} | {cat} | {imp} | {rev} | {rat} |".format(
                    ref=e.get("ref_span", " ".join(e.get("ref_tokens", []))) or "∅",
                    hyp=e.get("hyp_span", " ".join(e.get("hyp_tokens", []))) or "∅",
                    op=e["op"],
                    cat=e["primary_category"],
                    imp=e["semantic_impact"],
                    rev=e["review_status"],
                    rat=e.get("rationale", "").replace("|", "/"),
                )
            )
        lines.append("")

    lines.extend(
        [
            "## F — Meaningful error analysis",
            "",
            "Qualitative observations only (no entity F1 without annotations):",
            "",
        ]
    )
    for note in payload.get("meaningful_error_notes", []):
        lines.append(f"- {note}")
    if not payload.get("meaningful_error_notes"):
        lines.append("- _No curated notes attached._")

    lines.extend(
        [
            "",
            "Unavailable quantitative metrics:",
            "",
        ]
    )
    for name, reason in payload.get("unavailable_metrics", {}).items():
        lines.append(f"- `{name}`: {reason}")

    lines.extend(
        [
            "",
            "## G — Interpretation",
            "",
            "A model can show higher basic WER when it verbalizes numbers that "
            "the reference writes as digits (or vice versa). After "
            "`pl_wer_normalized_v1`, those formatting mismatches no longer "
            "inflate WER, so normalized WER better approximates recognition of "
            "spoken content for the supported equivalences.",
            "",
            "The normalizer is **not** a semantic understanding system: it "
            "applies deterministic, versioned surface rules. Homophones, "
            "negations, wrong quantities, and brand misspellings remain errors.",
            "",
            "## H — Limitations",
            "",
            "- N = 1 smoke recording.",
            "- Manually scripted / read speech.",
            "- Possible read-speech vs reference discrepancies; reference not "
            "independently verified against audio in this pipeline.",
            "- Polish morphology remains only partially covered "
            "(nominative cardinals; year ordinals collapse case).",
            "- Some homophones are acoustically indistinguishable.",
            "- This sample was used while developing normalization rules → "
            "**not** an independent held-out benchmark.",
            "- New normalizer performance must be tested on unseen data.",
            "- No confidence intervals or significance claims from one clip.",
            "",
            "## I — Next steps",
            "",
            "- Freeze `pl_wer_normalized_v1` after human audit of edge cases.",
            "- Human-audit taxonomy rows marked `auto_inferred`.",
            "- Run a 40-clip Common Voice Polish pilot with the frozen protocol.",
            "- Expand to a 200-clip holdout once the pipeline is validated.",
            "- Keep identical audio and protocol for both models; report corpus "
            "WER and paired per-clip differences with appropriate uncertainty.",
            "",
            "---",
            "",
            f"Generated at `{payload['created_at']}`. "
            "Legacy `results/evaluation/smoke_*` artifacts were not modified.",
            "",
        ]
    )
    return "\n".join(lines)


def write_markdown_v2(path: Path, payload: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_comparison_markdown_v2(payload), encoding="utf-8")
